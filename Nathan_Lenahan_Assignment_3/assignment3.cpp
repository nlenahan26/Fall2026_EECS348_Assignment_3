    void showNext() const { // Starts the method that displays the next Email to read

        const Email* e = heap.peekMax(); // Gets a read-only pointer to the highest-priority Email

        if (e == nullptr) { // Checks whether there are no unread emails
            cout << "There are no emails to read." << '\n' << '\n'; // Displays the empty-queue message without unnecessary stream flushing
            return; // Ends the method because there is no Email to display
        } // Ends the empty-queue check

        cout << "Next email:" << '\n'; // Displays the heading and moves to the next line
        cout << "\tSender: " << e->getSender() << '\n'; // Displays the sender using the Email getter
        cout << "\tSubject: " << e->getSubject() << '\n'; // Displays the subject using the Email getter
        cout << "\tDate: " << e->getDate() << '\n' << '\n'; // Displays the date followed by a blank line

    } // Ends the showNext method

    // The following markRead method is based on the original code generated by Claude
    // It was revised to display a message when READ is used on an empty queue, with help from ChatGPT
    // It removes the highest-priority unread Email after the CEO has read it
    void markRead() { // Starts the method that marks the next Email as read

        if (heap.peekMax() == nullptr) { // Checks whether there are no unread emails

            cout << "No emails to read." << '\n' << '\n'; // Tells the user there is no Email to remove

            return; // Ends the method because the queue is empty

        } // Ends the empty-queue check

        heap.removeMax(); // Removes the highest-priority unread Email without displaying it

    } // Ends the markRead method

    // The following showCount method is based on the original code generated by Claude
