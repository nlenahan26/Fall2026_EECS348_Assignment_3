    string sender; // Stores the sender category of the email
    string subject; // Stores the subject line of the email
    string date; // Stores the original date in MM-DD-YYYY format

    int senderRank; // Stores the numerical priority of the sender category
    int dateKey; // Stores the date as YYYYMMDD so dates can be compared numerically
    int sequence; // Stores arrival order and is used to break exact priority ties


public: // Makes the following constructors and public methods accessible outside the Email class

    // The following default Email constructor is from the original code generated by Claude
    // It creates an empty Email object with default values
    Email() // Starts the default Email constructor
        : sender(""), subject(""), date(""), // Initializes all string fields as empty
          senderRank(0), dateKey(0), sequence(0) {} // Initializes all integer fields to 0


    // The following parameterized Email constructor is from the original code generated by Claude
    // It creates an Email object using the sender, subject, date, and arrival sequence
    Email(const string& s, const string& subj, const string& d, int seq) // Starts the parameterized Email constructor
        : sender(s), subject(subj), date(d), sequence(seq) { // Stores the provided email information

        senderRank = rankFor(s); // Converts the sender category into its numerical priority
        dateKey = keyFor(d);     // Converts the date into YYYYMMDD format for comparison
    } // Ends the parameterized Email constructor

    // The following hasHigherPriorityThan method is from the original code generated by Claude
    // It returns true when this Email should be read before the other Email
    bool hasHigherPriorityThan(const Email& other) const { // Starts the priority comparison

        if (senderRank != other.senderRank) { // Checks whether the sender priorities are different
            return senderRank > other.senderRank; // Higher sender rank means higher priority
        } // Ends the sender-priority comparison

        if (dateKey != other.dateKey) { // Runs when sender priorities match but dates are different
            return dateKey > other.dateKey; // Newer date receives higher priority
        } // Ends the date comparison

        return sequence < other.sequence; // Earlier arrival wins when sender and date are identical
    } // Ends the hasHigherPriorityThan method

    // The following getter methods were added to the Claude-based Email class with help from ChatGPT
    // They provide read-only access to the Email information while keeping the data members private
    const string& getSender() const { // Starts the method that provides access to the sender
        return sender; // Returns a read-only reference to the Email's sender category
    } // Ends the getSender method
    const string& getSubject() const { // Starts the method that provides access to the subject
        return subject; // Returns a read-only reference to the Email's subject line
    } // Ends the getSubject method
    const string& getDate() const { // Starts the method that provides access to the date
        return date; // Returns a read-only reference to the Email's original date
    } // Ends the getDate method

private: // Makes the following helper methods usable only inside the Email class

    // The following rankFor method is from the original code generated by Claude
    // It converts each sender category into its required numerical priority
    static int rankFor(const string& s) { // Starts the sender-priority conversion

        if (s == "Boss")            return 5; // Gives Boss the highest priority
        if (s == "Subordinate")     return 4; // Gives Subordinate the second-highest priority
        if (s == "Peer")            return 3; // Gives Peer the middle priority
        if (s == "ImportantPerson") return 2; // Gives ImportantPerson the second-lowest priority

        return 1; // Gives OtherPerson the lowest priority
    } // Ends the rankFor method


    // The following keyFor method is from the original code generated by Claude
    // It converts a date from MM-DD-YYYY into YYYYMMDD so newer dates have larger values
    static int keyFor(const string& d) { // Starts the date conversion

        int month = stoi(d.substr(0, 2)); // Extracts and converts the month to an integer
        int day = stoi(d.substr(3, 2));   // Extracts and converts the day to an integer
        int year = stoi(d.substr(6, 4));  // Extracts and converts the year to an integer

        return year * 10000 + month * 100 + day; // Combines the values into YYYYMMDD format

    } // Ends the keyFor method

